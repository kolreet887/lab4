#!/bin/bash

# ==============================================================================
# Лабораторная работа: BASH-сценарий с диалоговым меню
# ==============================================================================

while true; do
    echo "=================================================="
    echo "                    ГЛАВНОЕ МЕНЮ                  "
    echo "=================================================="
    echo "1. Информация об авторе и назначении сценария"
    echo "2. Вычисление математического выражения (Формула 2.1)"
    echo "3. Копирование файлов из указанного места в заданное"
    echo "4. Очистка каталога с подтверждением"
    echo "5. Выход"
    echo "=================================================="
    read -p "Выберите пункт меню [1-5]: " CHOICE
    echo ""

    case "$CHOICE" in
        1)
            echo "--------------------------------------------------"
            echo "   ИНФОРМАЦИЯ ОБ АВТОРЕ И НАЗНАЧЕНИИ СЦЕНАРИЯ     "
            echo "--------------------------------------------------"
            echo "Автор: Студент (группа ИТД-11)"
            echo "Описание:"
            echo "Данный BASH-скрипт предназначен для выполнения"
            echo "диалоговых операций с пользователем:"
            echo " - Расчет показателя x по формуле 2.1;"
            echo " - Интерактивное копирование файлов;"
            echo " - Безопасная очистка подкаталога с запросом подтверждения."
            echo "--------------------------------------------------"
            echo ""
            ;;

        2)
            echo "--------------------------------------------------"
            echo "   ВЫЧИСЛЕНИЕ ВЫРАЖЕНИЯ (Формула 2.1)             "
            echo "   Формула: x = (№Компьютера + №По_журналу) * Возраст"
            echo "--------------------------------------------------"
            
            read -p "Введите номер компьютера: " COMP_NUM
            read -p "Введите ваш номер по журналу: " LOG_NUM
            read -p "Введите ваш возраст: " AGE

            # Проверка, что введены целые положительные числа
            if [[ "$COMP_NUM" =~ ^[0-9]+$ ]] && [[ "$LOG_NUM" =~ ^[0-9]+$ ]] && [[ "$AGE" =~ ^[0-9]+$ ]]; then
                X=$(( (COMP_NUM + LOG_NUM) * AGE ))
                echo ""
                echo ">>> Результат вычисления: x = ($COMP_NUM + $LOG_NUM) * $AGE = $X"
            else
                echo ""
                echo "Ошибка: Все параметры должны быть целыми числами!"
            fi
            echo "--------------------------------------------------"
            echo ""
            ;;

        3)
            echo "--------------------------------------------------"
            echo "   КОПИРОВАНИЕ ФАЙЛОВ                             "
            echo "--------------------------------------------------"
            read -p "Введите путь к исходному файлу/каталогу (источник): " SRC
            read -p "Введите путь назначения (куда копировать): " DEST

            if [ ! -e "$SRC" ]; then
                echo "Ошибка: Исходный файл или каталог '$SRC' не существует!"
            else
                # Создаем целевую директорию, если она не существует
                if [ -d "$SRC" ]; then
                    mkdir -p "$DEST"
                    cp -r "$SRC"/* "$DEST"/ 2>/dev/null
                else
                    mkdir -p "$(dirname "$DEST")"
                    cp -r "$SRC" "$DEST"
                fi

                if [ $? -eq 0 ]; then
                    echo ">>> Копирование успешно завершено!"
                else
                    echo ">>> Произошла ошибка при копировании."
                fi
            fi
            echo "--------------------------------------------------"
            echo ""
            ;;

        4)
            echo "--------------------------------------------------"
            echo "   ОЧИСТКА ПОДКАТАЛОГА С ПОДТВЕРЖДЕНИЕМ          "
            echo "--------------------------------------------------"
            read -p "Введите путь к подкаталогу для очистки: " TARGET_DIR

            if [ ! -d "$TARGET_DIR" ]; then
                echo "Ошибка: Указанный каталог '$TARGET_DIR' не существует или не является директорией!"
            else
                # Проверка, не пуст ли каталог
                if [ -z "$(ls -A "$TARGET_DIR")" ]; then
                    echo "Каталог '$TARGET_DIR' уже пуст."
                else
                    echo "Внимание! Все файлы и подкаталоги внутри '$TARGET_DIR' будут удалены."
                    read -p "Вы уверены, что хотите очистить '$TARGET_DIR'? (y/n): " CONFIRM
                    
                    case "$CONFIRM" in
                        [Yy]|[Дд])
                            rm -rf "$TARGET_DIR"/* "$TARGET_DIR"/.[!.]* 2>/dev/null
                            echo ">>> Каталог '$TARGET_DIR' успешно очищен."
                            ;;
                        *)
                            echo ">>> Операция очистки отменена пользователем."
                            ;;
                    esac
                fi
            fi
            echo "--------------------------------------------------"
            echo ""
            ;;

        5)
            echo "Выход из программы. До свидания!"
            exit 0
            ;;

        *)
            echo "Ошибка: Неверный пункт меню! Пожалуйста, выберите число от 1 до 5."
            echo ""
            ;;
    esac
done